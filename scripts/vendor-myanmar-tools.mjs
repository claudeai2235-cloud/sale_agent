import fs from "node:fs";
const root = "node_modules/myanmar-tools";
let det = fs.readFileSync(`${root}/src/zawgyi_detector.ts`, "utf8")
  .replace("<BASE64_DATA_PLACEHOLDER>", () => fs.readFileSync(`${root}/resources/zawgyiUnicodeModel.dat`, "base64"));
let conv = fs.readFileSync(`${root}/src/zawgyi_converter.ts`, "utf8")
  .replace("declare function getAllRulesZ2U(): TranslitRule[][]; // PLACEHOLDER", () => fs.readFileSync(`${root}/resources/Z2U.js`, "utf8").replace(/^\/\*[\s\S]*?\*\//, ""))
  .replace(/declare function getAllRulesU2Z\(\): TranslitRule\[\]\[\]; \/\/ PLACEHOLDER/, "function getAllRulesU2Z(): TranslitRule[][] { throw new Error('not bundled'); }")
  .replace(/declare function getAllRulesZNorm\(\): TranslitRule\[\]\[\]; \/\/ PLACEHOLDER/, "function getAllRulesZNorm(): TranslitRule[][] { throw new Error('not bundled'); }")
  .replace(/^\/\*[\s\S]*?\*\//, "");
// keep NODEJS preprocessor branches, drop the browser (!NODEJS) ones
det = det.replace(/\/\/ @if !NODEJS[\s\S]*?\/\/ @endif/g, "");
det = det.replace(/new Buffer\(/g, "Buffer.from(");
const out = `/* eslint-disable */\n// @ts-nocheck\n// GENERATED by scripts/vendor-myanmar-tools.mjs — do not edit.\n${det}\n${conv}\n`;
fs.writeFileSync("src/lib/vendor/myanmar-tools.ts", out);
console.log("ok", out.length);
